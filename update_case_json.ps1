# ── JSON 삽입 헬퍼: docLines 배열을 JSON 문자열 배열로 변환 ───────────────
function Make-DocJson {
    param(
        [string]$style,
        [string[]]$lines
    )

    # 인용 부호 이스케이프
    $result = [System.Collections.Generic.List[string]]::new()
    $result.Add("  `"docStyle`": `"$style`",")
    $result.Add("  `"docLines`": [")

    for ($i = 0; $i -lt $lines.Count; $i++) {
        $escaped = $lines[$i] -replace '\\', '\\\\' -replace '"', '\"'
        if ($i -lt $lines.Count - 1) {
            $result.Add("    `"$escaped`",")
        } else {
            $result.Add("    `"$escaped`"")
        }
    }
    $result.Add("  ],")
    return ,$result.ToArray()
}

# ── 케이스 JSON 파일 업데이트 루프 ───────────────────────────────────────
$totalUpdated = 0

foreach ($num in $D.Keys) {
    $entry    = $D[$num]
    $jsonLines = Make-DocJson -style $entry.style -lines $entry.lines

    $files = Get-ChildItem $storyDir -Filter "case_${num}*.json" -ErrorAction SilentlyContinue

    foreach ($f in $files) {
        $src = [System.IO.File]::ReadAllLines($f.FullName, [System.Text.Encoding]::UTF8)

        $out     = [System.Collections.Generic.List[string]]::new()
        $inserted = $false

        foreach ($line in $src) {
            # bgImage 줄 제거
            if ($line -match '"bgImage"') { continue }

            $out.Add($line)

            # "id": 줄 바로 다음에 docStyle + docLines 삽입 (중복 방지)
            if (!$inserted -and $line -match '"id"\s*:') {
                foreach ($jl in $jsonLines) { $out.Add($jl) }
                $inserted = $true
            }
        }

        [System.IO.File]::WriteAllLines($f.FullName, $out.ToArray(), $enc)
        $totalUpdated++
    }
}

Write-Host "Done. Updated $totalUpdated JSON files."
